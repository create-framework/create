#!/bin/sh
# Writes src/create/text/_noto.mojo: the packaged Noto faces in
# src/create/text/fonts/ as base64 string literals, so they are compiled
# into the library and a program finds them wherever it runs. Mojo has no
# way to read a file at compile time, and a string literal holds code points,
# not bytes, hence base64. Run it after changing a face there.
#
#   pixi run embed-fonts
set -eu

fonts=src/create/text/fonts
out=src/create/text/_noto.mojo

literal() {
    printf 'comptime %s = (\n' "$1"
    base64 <"$fonts/$2" | tr -d '\n' | fold -w 72 | awk '{ print "    \"" $0 "\"" }'
    printf ')\n"""%s, base64."""\n' "$2"
}

{
    printf '%s\n' \
        '# Generated by scripts/embed_fonts.sh from fonts/; do not edit.' \
        '#' \
        '# The Noto faces, Copyright 2022 The Noto Project Authors, under the SIL' \
        '# Open Font License 1.1 (fonts/OFL.txt). Decoded by `font.mojo`.' \
        '' \
        '# Unformatted: `mojo format` takes time quadratic in a literal'"'"'s lines.' \
        '# fmt: off' \
        ''
    literal _NOTO_SANS NotoSans.ttf
    printf '\n\n'
    literal _NOTO_SANS_ITALIC NotoSans-Italic.ttf
    printf '\n\n'
    literal _NOTO_SANS_SYMBOLS NotoSansSymbols.ttf
    printf '# fmt: on\n'
} >"$out"
